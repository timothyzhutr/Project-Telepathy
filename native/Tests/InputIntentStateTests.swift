import Foundation

@main struct InputIntentStateTests {
  static func check(_ ok: Bool, _ message: String) {
    if !ok { fputs("FAIL: \(message)\n", stderr); exit(1) }
  }
  static func main() {
    var retained = InputIntentState()
    retained.update(raw: "hello", revision: 1)
    check(retained.apply("english", revision: 1), "Learn an English default")
    retained.invalidate(revision: 2)
    retained.update(raw: "a", revision: 3)
    check(retained.english, "A committed word must seed the next word's language before inference")
    check(retained.apply("uncertain", revision: 3) && retained.english,
      "Uncertain decisions must preserve the location's last definite language")
    retained.invalidate(revision: 4, resetDefault: true)
    retained.update(raw: "a", revision: 5)
    check(!retained.english && retained.defaultLanguage == nil, "A new cursor location must clear the previous default")
    retained.invalidate(revision: 6)
    check(retained.rememberScreenHint("english") && !retained.english,
      "A prewarmed hint must seed the default without a phantom pending word")
    retained.update(raw: "a", revision: 7)
    check(retained.english, "The first letter must use a prewarmed hint immediately")
    check(retained.apply("chinese", revision: 7) && retained.defaultLanguage == "chinese",
      "Fresh input can replace the remembered screen default")
    check(!retained.rememberScreenHint("english"), "A screen hint must not replace a text decision")
    retained.forceChinese(remember: true)
    retained.invalidate(revision: 8)
    retained.update(raw: "he", revision: 9)
    check(!retained.english && retained.defaultLanguage == "chinese", "An explicit Chinese choice seeds subsequent words")
    retained.startLiteralRun()
    _ = retained.passLiteralKey(32)
    retained.invalidate(revision: 10)
    retained.update(raw: "a", revision: 11)
    check(!retained.english && retained.defaultLanguage == "chinese",
      "A temporary capital or URL must preserve the Chinese default for the next word")
    var firstCapital = InputIntentState()
    firstCapital.startLiteralRun()
    _ = firstCapital.passLiteralKey(32)
    firstCapital.invalidate(revision: 1)
    firstCapital.update(raw: "a", revision: 2)
    check(firstCapital.english, "A capital may seed English when no definite language default exists")
    var state = InputIntentState()
    state.update(raw: "he", revision: 1)
    check(state.apply("english", revision: 1), "A current English judgment must be accepted")
    check(state.english, "English must preserve keyboard text")
    check(state.action(for: 32) == .space, "English Space must insert a literal space")
    check(state.action(for: 0xff0d) == .commitAndPass, "English Return must reach the host after committing text")
    check(state.action(for: 46) == .commitAndPass, "English punctuation must reach the host literally")
    check(state.action(for: 39) == .none, "A contraction apostrophe must stay in the word")
    check(state.action(for: 0xff54) == .chinese, "Down must restore Chinese choices")
    state.update(raw: "help", revision: 2)
    check(state.english, "An English word must stay visible while more letters arrive")
    check(!state.apply("chinese", revision: 1), "A late decision for shorter input must be ignored")
    check(state.apply("chinese", revision: 2) && !state.english, "Fresh context can restore Chinese")
    state.forceChinese()
    check(!state.apply("english", revision: 2), "Manual Chinese selection must override the model")
    state.update(raw: "helper", revision: 3)
    check(!state.apply("english", revision: 3), "Manual intent must persist through this composition")
    state.invalidate(revision: 4)
    check(!state.apply("english", revision: 3), "Commit/deactivation must discard pending intent")
    state.update(raw: "can", revision: 5)
    check(state.apply("english", revision: 5), "A new word must clear the manual override")
    state.update(raw: "nihao", revision: 6)
    check(state.english, "Replacing a word at the same location must inherit its English default")
    check(state.apply("uncertain", revision: 6) && state.english, "Uncertain input must retain the last definite decision")
    check(state.apply("chinese", revision: 6) && !state.english, "Fresh Chinese evidence replaces the default")
    check(state.action(for: 32) == .none, "Chinese Space must retain Rime selection behavior")
    state.startLiteralRun()
    check(state.passLiteralKey(65), "An explicit capital must preserve its case")
    check(state.passLiteralKey(47), "URL punctuation must stay ASCII")
    check(state.passLiteralKey(0xff08), "Backspace must reach the host within a literal run")
    check(state.passLiteralKey(32), "The terminating space must reach the host")
    check(!state.passLiteralKey(97), "The next word must resume automatic language decisions")
    state.startLiteralRun()
    state.invalidate(revision: 7)
    check(!state.passLiteralKey(97), "Deactivation must clear literal passthrough")
    state.update(raw: "a", revision: 8)
    check(state.applyInitialHint("english", revision: 8), "A screen hint may route the uncommitted first word")
    check(state.english, "An English screen hint must show literal typing immediately")
    state.update(raw: "an", revision: 9)
    check(!state.applyInitialHint("chinese", revision: 8), "A stale composition hint must be ignored")
    check(state.apply("chinese", revision: 9) && !state.english, "Text context must override a screen hint")
    check(!state.applyInitialHint("english", revision: 9), "A screen hint must never override a contextual decision")
    state.invalidate(revision: 10)
    state.update(raw: "ni", revision: 11)
    state.forceChinese()
    check(!state.applyInitialHint("english", revision: 11), "Manual Chinese must override a late screen hint")
    state.invalidate(revision: 12)
    check(!state.applyInitialHint("english", revision: 12), "A late hint must never alter committed text")
    print("PASS: English boundaries, fresh/stale language decisions, manual override, commit reset")
  }
}
